//cuenta hacia atras//
let contador=5;
while (contador > 0) {
console.log("El despegue será en " + contador + " segundos...");
  contador--;
}
console.log("¡Despegue!");


// Cuenta hacia arriba//
contador = 1;
while (contador <= 5) {
  console.log(`Han pasado ${contador} segundos desde el despegue...`);
  contador++;
}
console.log("Fin de la simulación")